template<typename T, std::size_t N>
struct Internal_Scalar_Unrolled{
    static int64_t load_add(T* data, size_t stride){
        if constexpr (N > 0){
            return Internal_Scalar_Unrolled<T, N-1>::load_add(data, stride) + data[stride * N];
        }else{
            return data[stride * N];
        }
    }
};

template<typename T,std::size_t N>
struct Loop_Scalar_Unrolled{
    static int64_t run(T* data, size_t stride){
        int64_t result = 0;
        for(size_t i = 0; i < stride; i++){
            result += Internal_Scalar_Unrolled<T ,N-1>::load_add(&data[i], stride);
        }    
        return result;
    } 
};

